#!/usr/bin/env node
/**
 * Regenerates nodes/FiscalData/catalog.ts from the official Fiscal Data metadata endpoint.
 *
 * Usage:
 *   npm run generate:catalog                 # downloads metadata from the API
 *   npm run generate:catalog -- ./meta.json  # uses a local copy of the metadata
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const METADATA_URL = 'https://api.fiscaldata.treasury.gov/services/dtg/metadata/';
const ENDPOINT_PREFIX = '/services/api/fiscal_service';
const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, '../nodes/FiscalData/catalog.ts');

async function loadMetadata() {
	const localPath = process.argv[2];
	if (localPath) return JSON.parse(await readFile(localPath, 'utf8'));

	for (let attempt = 1; attempt <= 5; attempt++) {
		try {
			const res = await fetch(METADATA_URL, { headers: { Accept: 'application/json' } });
			if (!res.ok) throw new Error(`HTTP ${res.status}`);
			return await res.json();
		} catch (error) {
			console.warn(`Attempt ${attempt} failed: ${error.message}`);
			await new Promise((r) => setTimeout(r, attempt * 2000));
		}
	}
	throw new Error('Could not download Fiscal Data metadata');
}

const clean = (text, max = 300) => {
	const t = String(text ?? '')
		.replace(/\s+/g, ' ')
		.trim();
	return t.length > max ? `${t.slice(0, max - 1).trimEnd()}…` : t;
};

const metadata = await loadMetadata();

const datasets = metadata
	.map((ds) => ({
		id: ds.dataset_id,
		title: clean(ds.title, 150),
		description: clean(ds.short_description),
		path: ds.dataset_path,
		updateFrequency: ds.update_frequency ?? '',
		endpoints: [...ds.apis]
			.filter(
				(api) =>
					typeof api.endpoint_txt === 'string' && api.endpoint_txt.startsWith(ENDPOINT_PREFIX),
			)
			.sort((a, b) => (a.api_sort_order_nbr ?? 0) - (b.api_sort_order_nbr ?? 0))
			.map((api) => ({
				path: api.endpoint_txt.slice(ENDPOINT_PREFIX.length),
				name: clean(api.table_name, 150),
				description: clean(api.table_description),
				earliestDate: api.earliest_date ?? '',
				latestDate: api.latest_date ?? '',
				fields: [...api.fields]
					.sort((a, b) => (a.sort_order_nbr ?? 0) - (b.sort_order_nbr ?? 0))
					.map((f) => [f.column_name, clean(f.pretty_name, 150), f.data_type ?? 'STRING']),
			})),
	}))
	.filter((ds) => ds.endpoints.length > 0)
	.sort((a, b) => a.title.localeCompare(b.title));

const endpointCount = datasets.reduce((n, ds) => n + ds.endpoints.length, 0);

const source = `// AUTO-GENERATED by scripts/generate-catalog.mjs — do not edit by hand.
// Source: ${METADATA_URL}
// Generated: ${new Date().toISOString().slice(0, 10)} (${datasets.length} datasets, ${endpointCount} endpoints)

/** [column_name, pretty_name, data_type] */
export type CatalogField = [string, string, string];

export interface CatalogEndpoint {
	path: string;
	name: string;
	description: string;
	earliestDate: string;
	latestDate: string;
	fields: CatalogField[];
}

export interface CatalogDataset {
	id: string;
	title: string;
	description: string;
	path: string;
	updateFrequency: string;
	endpoints: CatalogEndpoint[];
}

export const DATASETS: CatalogDataset[] = ${JSON.stringify(datasets)};
`;

await writeFile(outFile, source, 'utf8');
console.log(`Wrote ${outFile}: ${datasets.length} datasets, ${endpointCount} endpoints`);
